import type { Prisma } from "@/generated/prisma/client";
import { getProjectScore, getProjectStack } from "@/lib/project-stats";

type ProjectWithData = Prisma.ProjectGetPayload<{
  include: {
    projectStages: { include: { stage: true; recommendations: { include: { nistControl: true } } } };
  };
}>;

/**
 * Escapes markdown-significant characters for values interpolated into
 * generated .md files (project name/description, AI-generated titles).
 * Pipes, backticks, brackets and angle brackets are the risky ones for
 * tables, code spans, links and HTML injection.
 */
function escapeMd(s: string): string {
  return s
    .replaceAll("|", "\\|")
    .replaceAll("`", "\\`")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll(/\[([^\]]*)\]\((.*?)\)/g, "[$1]&lpar;$2&rpar;");
}

function deploymentSection(project: ProjectWithData): string[] {
  const files =
    ((project.globalSpec as Record<string, unknown> | null)?.codeArtifacts as
      | Record<string, string>
      | null) ?? {};
  const hasDocker = Object.keys(files).some((f) => /dockerfile|docker-compose/i.test(f));
  const hasVercel = Object.keys(files).some((f) => /vercel\.json/i.test(f));
  const hasNetlify = Object.keys(files).some((f) => /netlify\.toml/i.test(f));
  const lines: string[] = ["## 5. Deployment", ""];
  if (hasDocker) {
    lines.push("### Docker", "", "```bash", "docker build -t my-app .", "docker run -p 3000:3000 my-app", "```", "");
  } else if (hasVercel || hasNetlify) {
    lines.push(
      "### Serverless host",
      "",
      "The project includes a platform config file; connect the repository to your platform account and it will build automatically.",
      "",
    );
  } else {
    lines.push(
      "### Node.js host",
      "",
      "```bash",
      "npm ci",
      "npm run build",
      "npm start",
      "```",
      "",
      "Set the environment variables listed in `.env.example` on your host.",
      "",
    );
  }
  lines.push(
    "Environment variables are read from the host environment (never committed):",
    "",
    "```env",
    "DATABASE_URL=postgresql://...",
    "SESSION_SECRET=replace-with-a-long-random-secret",
    "```",
    "",
  );
  return lines;
}

export function buildManualBook(project: ProjectWithData): string {
  const stack = getProjectStack(project);
  const files =
    ((project.globalSpec as Record<string, unknown> | null)?.codeArtifacts as
      | Record<string, string>
      | null) ?? {};
  const fileList = Object.keys(files)
    .map((f) => `  - \`${escapeMd(f)}\``)
    .join("\n");

  const lines = [
    `# ${escapeMd(project.name)} — Manual Book`,
    "",
    `> Generated by SecureSDLC AI (NIST SP 800-218 engine).`,
    "",
    "## 1. Overview",
    "",
    escapeMd(project.description ?? "No description provided."),
    "",
    `- **Version:** ${project.currentVersion}`,
    `- **Recommended stack:** ${escapeMd(stack)}`,
    `- **Output language:** ${project.outputLanguage}`,
    "",
    "## 2. Project Structure",
    "",
    fileList || "  - (no files yet)",
    "",
    "## 3. Getting Started",
    "",
    "1. Clone/copy the project files.",
    "2. Copy `.env.example` to `.env` and fill in required values.",
    "3. Install dependencies and start the development server:",
    "",
    "```bash",
    "npm install",
    "npm run dev",
    "```",
    "",
    "## 4. Security Notes",
    "",
    "- Secrets must live in environment variables, never in source code.",
    "- The repository includes a DevSecOps CI/CD pipeline (`.github/workflows/security.yml`).",
    "- For questions, re-open this project in SecureSDLC and chat with the AI.",
    "",
    ...deploymentSection(project),
  ];
  return lines.join("\n");
}

export function buildComplianceReport(project: ProjectWithData): string {
  const score = getProjectScore(project);
  const rows: { task: string; title: string; iso: string; status: string }[] = [];
  const appliedTasks = new Set<string>();
  const appliedIso = new Set<string>();
  const implementedByTask = new Map<string, boolean>();

  for (const ps of project.projectStages) {
    for (const rec of ps.recommendations) {
      const isoMapping = rec.nistControl && Array.isArray(rec.nistControl.iso27001Mapping)
        ? rec.nistControl.iso27001Mapping.filter((value): value is string => typeof value === "string")
        : [];
      if (rec.isApplied && rec.nistControl) {
        appliedTasks.add(rec.nistControl.taskCode);
        for (const iso of isoMapping) appliedIso.add(iso);
      }
      const task = rec.nistControl?.taskCode ?? "—";
      if (task !== "—") {
        // A task is "Implemented" if any recommendation for it is applied.
        const current = implementedByTask.get(task) ?? false;
        implementedByTask.set(task, current || rec.isApplied);
      }
      rows.push({
        task,
        title: rec.nistControl?.title ?? rec.title,
        iso: isoMapping.join(", ") || "—",
        status: rec.isApplied ? "Implemented" : "Recommended",
      });
    }
  }

  // Dedupe by task; prefer the "Implemented" row when statuses differ.
  const byTask = new Map<string, (typeof rows)[number]>();
  for (const r of rows) {
    if (r.task === "—") continue; // drop unmapped noise rows
    const existing = byTask.get(r.task);
    if (!existing) {
      byTask.set(r.task, r);
    } else if (existing.status !== "Implemented" && r.status === "Implemented") {
      byTask.set(r.task, r);
    }
  }
  const uniqueRows = [...byTask.values()];

  const lines = [
    `# ISO 27001:2022 Compliance Report (Concept)`,
    "",
    `**Project:** ${escapeMd(project.name)}  `,
    `**Version:** ${project.currentVersion}  `,
    `**Framework:** NIST SP 800-218 (SSDF v1.1) → ISO 27001:2022 Annex A crosswalk`,
    "",
    `## Executive Summary`,
    "",
    `The website was produced through a 5-stage AI-guided secure SDLC. ` +
      `Security controls are grounded in NIST SSDF tasks and mapped to ISO 27001:2022 Annex A controls.`,
    "",
    `**Security Score:** ${score}/100`,
    "",
    `**Controls implemented:** ${appliedTasks.size} NIST tasks → ${appliedIso.size} ISO Annex A controls.`,
    "",
    "## Crosswalk Matrix",
    "",
    "| NIST SSDF Task | Title | ISO 27001:2022 Annex A | Status |",
    "|---|---|---|---|",
    ...uniqueRows.map(
      (r) => `| ${escapeMd(r.task)} | ${escapeMd(r.title)} | ${escapeMd(r.iso)} | ${r.status} |`,
    ),
    "",
    "## Gap Analysis",
    "",
    ...(uniqueRows.length
      ? uniqueRows
          .filter((r) => r.status !== "Implemented")
          .map(
            (r) =>
              `- **${escapeMd(r.task)}** (${escapeMd(r.iso)}): ${escapeMd(r.title)} — not yet implemented.`,
          )
      : ["- No recommendations were mapped to NIST tasks yet."]),
    "",
    "> This report is auto-generated by SecureSDLC. It is an implementation-guidance artifact, not a formal certification.",
    "",
  ];
  return lines.join("\n");
}

export function buildSecurityWorkflowYaml(): string {
  return [
    "name: SecureSDLC Security Pipeline",
    "on:",
    "  push:",
    "    branches: [main, master]",
    "  pull_request:",
    "",
    "jobs:",
    "  security:",
    "    runs-on: ubuntu-latest",
    "    steps:",
    "      - uses: actions/checkout@v4",
    "      - name: Run security scanner (npm audit)",
    "        run: |",
    "          npm audit --omit=dev || true",
    "      - name: Run Trivy scanner",
    "        uses: aquasecurity/trivy-action@master",
    "        with:",
    "          scan-type: 'fs'",
    "          scan-ref: '.'",
    "          format: 'sarif'",
    "          output: 'trivy-results.sarif'",
    "      - name: Upload SARIF to GitHub Security tab",
    "        uses: github/codeql-action/upload-sarif@v3",
    "        with:",
    "          sarif_file: 'trivy-results.sarif'",
    "",
  ].join("\n");
}

export function buildReadme(project: ProjectWithData): string {
  const score = getProjectScore(project);
  return [
    `# ${escapeMd(project.name)}`,
    "",
    `> Generated with SecureSDLC — NIST SP 800-218 engine · ISO 27001:2022 crosswalk.`,
    "",
    score != null ? `**Security Score:** ${score}/100` : "**Security Score:** not scored yet",
    "",
    "## Docs",
    "",
    "- [Manual Book](./docs/MANUAL-BOOK.md)",
    "- [ISO 27001:2022 Compliance Report](./docs/ISO-27001-COMPLIANCE.md)",
    "",
    "## DevSecOps",
    "",
    "A security pipeline runs on every push (`.github/workflows/security.yml`): npm audit + Trivy + SARIF upload.",
    "",
  ].join("\n");
}
