"""Generate src/lib/site-templates.ts and public/templates/CREDITS.md from sources.json + capture-report.json.

Only pages the capture report marks "ok" (and whose images exist) are listed. Run after capture.py:
    python scripts/templates/build-data.py
"""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
PUBLIC = ROOT / "public"

sources = json.loads((HERE / "sources.json").read_text("utf-8"))
report = json.loads((HERE / "capture-report.json").read_text("utf-8"))["templates"]

CATEGORY_TITLES = {
    "marketplace": "Marketplace",
    "ecommerce": "E-commerce",
    "lms": "LMS",
    "saas": "SaaS",
    "clinic": "Clinic",
    "company": "Company",
    "news": "News",
    "api": "API",
}


def q(value) -> str:
    return "null" if value is None else json.dumps(value, ensure_ascii=False)


def web(path: Path) -> str:
    return "/" + path.relative_to(PUBLIC).as_posix()


lines = [
    "/**",
    " * Real open-source website templates shown in the FUSE gallery: three per category, each with",
    " * screenshots of its pages. GENERATED by scripts/templates/build-data.py from",
    " * scripts/templates/sources.json + capture-report.json; edit those and regenerate.",
    " */",
    'import type { CategoryId } from "./site-categories";',
    "",
    "export type TemplatePage = { id: string; src: string; thumb: string };",
    "export type SiteTemplate = {",
    "  slug: string;",
    "  name: string;",
    "  source: string;",
    "  license: string;",
    "  licenseUrl: string;",
    "  attribution: string | null;",
    "  /** First template of a category: its colours match the hero mood. */",
    "  mood: boolean;",
    "  mobile: string;",
    "  pages: readonly TemplatePage[];",
    "};",
    "",
    "export const SITE_TEMPLATES: Record<CategoryId, readonly [SiteTemplate, SiteTemplate, SiteTemplate]> = {",
]
credits = [
    "# Template open-source",
    "",
    "Tangkapan layar dari demo publik/salinan lokal template open-source; hak cipta tetap milik pembuatnya.",
    "",
    "| Kategori | Nama | Sumber | Lisensi | Atribusi |",
    "|---|---|---|---|---|",
]

for category, templates in sources.items():
    assert len(templates) == 3, category
    lines.append(f"  {category}: [")
    for i, tpl in enumerate(templates):
        key = f"{category}/{tpl['slug']}"
        folder = PUBLIC / "templates" / category / tpl["slug"]
        ok = {p["id"] for p in report[key]["pages"] if p["status"] == "ok"}
        pages = [p["id"] for p in tpl["pages"] if p["id"] in ok and (folder / f"{p['id']}.webp").exists()]
        assert len(pages) >= 4, f"{key}: only {len(pages)} pages passed"
        assert pages[0] == tpl["pages"][0]["id"], f"{key}: main page {tpl['pages'][0]['id']} was rejected"
        mobile = folder / "home@m.webp"
        assert mobile.exists(), f"{key}: missing mobile shot"
        lines += [
            "    {",
            f"      slug: {q(tpl['slug'])},",
            f"      name: {q(tpl['name'])},",
            f"      source: {q(tpl['source'])},",
            f"      license: {q(tpl['license'])},",
            f"      licenseUrl: {q(tpl['licenseUrl'])},",
            f"      attribution: {q(tpl['attribution'])},",
            f"      mood: {'true' if i == 0 else 'false'},",
            f"      mobile: {q(web(mobile))},",
            "      pages: [",
        ]
        for pid in pages:
            src, thumb = web(folder / f"{pid}.webp"), web(folder / f"{pid}@thumb.webp")
            lines.append(f"        {{ id: {q(pid)}, src: {q(src)}, thumb: {q(thumb)} }},")
        lines += ["      ],", "    },"]
        cells = [CATEGORY_TITLES[category], tpl["name"], tpl["source"], f"[{tpl['license']}]({tpl['licenseUrl']})", tpl["attribution"] or "-"]
        credits.append("| " + " | ".join(c.replace("|", "\\|") for c in cells) + " |")
    lines.append("  ],")

lines += [
    "};",
    "",
    "export function templatesFor(id: CategoryId): readonly SiteTemplate[] {",
    "  return SITE_TEMPLATES[id];",
    "}",
    "",
]

(ROOT / "src" / "lib" / "site-templates.ts").write_text("\n".join(lines), "utf-8")
(PUBLIC / "templates" / "CREDITS.md").write_text("\n".join(credits) + "\n", "utf-8")
print("wrote src/lib/site-templates.ts and public/templates/CREDITS.md")
